import json

import pandas as pd

from config import DATA, DOCS, RESULTS, ROOT


def load_json(path):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def load_csv(name):
    path = RESULTS / name
    return pd.read_csv(path) if path.exists() else pd.DataFrame()


def table(frame):
    head = "| " + " | ".join(str(column) for column in frame.columns) + " |\n"
    head += "|" + "|".join(["---"] * len(frame.columns)) + "|\n"
    rows = "".join("| " + " | ".join(str(value) for value in row) + " |\n"
                   for row in frame.itertuples(index=False))
    return head + rows


def main():
    corpus = load_json(DATA / "corpus_stats.json")
    selection = load_json(DATA / "selection.json")
    index = load_json(DATA / "index_manifest.json")
    split = load_json(DATA / "split.json")
    stats = load_json(RESULTS / "stats.json")
    headline_stats = load_json(RESULTS / "headline_stats.json")
    headline_ablation = load_csv("headline_ablation.csv")
    headline_subgroup = load_csv("headline_subgroup.csv")
    headline_latency = load_json(RESULTS / "headline_latency.json")
    baseline = load_json(RESULTS / "baseline_rerun.json")
    records = load_json(DATA / "records.json")
    condition = load_csv("condition_metrics.csv")
    subsets = load_csv("subset_metrics.csv")
    ablation = load_csv("ablation.csv")
    subgroup = load_csv("subgroup_metrics.csv")
    unsupervised = load_csv("unsupervised_metrics.csv")
    quality = load_csv("quality_audit.csv")
    latency = load_json(RESULTS / "latency.json")
    total_pdfs = len(list(DOCS.glob("*.pdf"))) if DOCS.exists() else 0

    audit_value = lambda metric: int(quality.loc[quality.metric == metric, "value"].iloc[0]) if not quality.empty and (quality.metric == metric).any() else 0

    names = {"pred_a": "A plain LLM", "pred_b": "B RAG", "pred_c": "C RAG self-consistency",
             "pred_d": "D verified pipeline"}
    real = subsets[(subsets.get("subset") == "real_chunk")] if not subsets.empty else pd.DataFrame()
    if not real.empty:
        real = real.copy()
        real["condition"] = real["condition"].map(names)

    parts = ["# Groundedness Verification for NIT Jamshedpur Academic Queries\n\n"]
    parts.append("Tables and statistics below are generated by `make_docs.py` from `data/` and `results/` artifacts. "
                 "The reported headline uses only claims with a source chunk; generated absence probes are inventoried but excluded.\n\n")
    parts.append("## Scope and exclusions\n\n")
    parts.append("- No MFAQ, synthetic public-university, meta-learner or human-review results are reported.\n")
    test_real = int(split.get("source_test_claims", 0))
    parts.append(f"- The {split.get('absent_claims', '')} model-generated absence probes are not NITJ facts and are excluded from every headline table and statistic.\n")
    parts.append(f"- The {test_real} reported test claims are source-backed: verbatim sentences or controlled one-fact counterfactuals with `source_chunk_id` and `original_value`.\n")
    parts.append("- Every model-evaluation number below is reproduced by `python reproduce.py --check`; per-claim provenance is in `results/claim_ledger.csv`.\n\n")

    parts.append("## Corpus\n\n")
    parts.append(f"- Local PDF collection: {total_pdfs} files; {selection.get('pool_size', '')} passed the text/date filter; "
                 f"{corpus.get('pdfs_selected', '')} were selected and {corpus.get('pdfs_parsed', '')} parsed.\n")
    parts.append(f"- Chunks: {corpus.get('chunks_dedup', '')} after removing {corpus.get('duplicates_removed', '')} duplicate bodies.\n")
    parts.append(f"- Prose chunks: {corpus.get('prose_chunks', '')}; table chunks: {corpus.get('table_chunks', '')}.\n")
    parts.append(f"- Chunks with a parsed issue date: {corpus.get('with_date', '')}; with a reference number: {corpus.get('with_ref', '')}.\n")
    parts.append(f"- Date range: {corpus.get('date_range', ['', ''])[0]} to {corpus.get('date_range', ['', ''])[1]}.\n")
    parts.append(f"- Indexed vectors: {index.get('chunks', '')} at {index.get('dim', '')} dimensions with `{index.get('emb_model', '')}`.\n\n")

    test_fragment = audit_value("test_fragment")
    test_hedge = audit_value("test_hedge")
    test_placeholder = audit_value("test_placeholder")
    placeholder_word = "placeholder" if test_placeholder == 1 else "placeholders"
    parts.append("## Benchmark\n\n")
    labels = split.get("labels", {})
    source_test = int(split.get("source_test_claims", audit_value("test_real_chunk")))
    source_dev = int(split.get("source_dev_claims", int(split.get("constructed_claims", 0)) - source_test))
    parts.append(f"- Audit inventory: {split.get('total', '')} claims = {split.get('constructed_claims', '')} source-backed "
                 f"+ {split.get('absent_claims', '')} generated absence probes.\n")
    parts.append(f"- Reported benchmark: {split.get('constructed_claims', '')} source-backed claims = {source_dev} dev + {source_test} test. "
                 f"The {split.get('absent_claims', '')} generated probes are excluded from all headline results.\n")
    parts.append(f"- Source-backed labels: {labels.get('true', '')} true and {labels.get('false', '')} controlled false. "
                 f"The {labels.get('unverifiable', '')} unverifiable probes are generated and excluded.\n")
    parts.append(f"- Split: {source_dev} dev and {source_test} test source-backed claims; "
                 f"{split.get('test_absent', '')} generated test probes are excluded.\n")
    parts.append(f"- Source documents with constructed claims: {split.get('dev_docs', '')} dev and "
                 f"{split.get('test_docs', '')} test.\n")
    parts.append(f"- Source-backed test quality: {test_real} claims, {audit_value('test_real_chunk_fragment')} fragments, "
                 f"{audit_value('test_real_chunk_hedge')} hedges, {audit_value('test_real_chunk_placeholder')} placeholders.\n")
    parts.append("- `tau_pass` and `tau_contra` are tuned on dev; weights are fixed at 0.40/0.25/0.35 and are not learned.\n\n")

    if not real.empty:
        parts.append(f"## Main result ({source_test} source-backed test claims)\n\n")
        parts.append(table(real[["condition", "n", "accuracy", "macro_f1", "missed_falsehood_rate", "abstention_rate"]]))
        parts.append("\n")


    if headline_stats:
        mb = headline_stats.get("mcnemar_d_vs_b", {})
        bb = headline_stats.get("bootstrap_d_minus_b", {})
        parts.append("## Statistics (source-backed subset)\n\n")
        parts.append(f"- Scored source-backed test claims: {headline_stats.get('n_scored', '')}; "
                     f"excluded generated absence probes: {headline_stats.get('n_excluded_generated', '')}.\n")
        parts.append(f"- McNemar D vs B: D better on {mb.get('d_better', '')}, B better on {mb.get('b_better', '')}, "
                     f"p = {mb.get('p_value', '')}.\n")
        parts.append(f"- Paired bootstrap accuracy delta D - B: {bb.get('delta', '')} "
                     f"({bb.get('ci_low', '')} to {bb.get('ci_high', '')}).\n")
        parts.append(f"- Judge backend: {headline_stats.get('judge_backend', '')}.\n")
        parts.append(f"- Brier score (D, true/false): {headline_stats.get('brier_d', '')}.\n\n")

    if not headline_ablation.empty:
        parts.append("## Gate ablation (source-backed test set)\n\n")
        parts.append(table(headline_ablation))
        parts.append("\n")
        cascade = headline_ablation[headline_ablation["rule"] == "cascade"]
        f_only = headline_ablation[headline_ablation["rule"] == "f_only"]
        g_only = headline_ablation[headline_ablation["rule"] == "g_only"]
        if len(cascade) and len(f_only) and len(g_only):
            delta = round(float(cascade["accuracy"].iloc[0]) - float(f_only["accuracy"].iloc[0]), 4)
            parts.append(f"Cascade minus F-only accuracy: {delta}. A G-only gate scores "
                         f"{g_only['accuracy'].iloc[0]} versus cascade {cascade['accuracy'].iloc[0]}; "
                         "the cascade is not established as the best rule on this subset.\n\n")

    if not headline_subgroup.empty:
        parts.append("## Subgroup: multi-fact vs single-fact claims (source-backed test)\n\n")
        parts.append(table(headline_subgroup))
        parts.append("\n")

    if headline_latency:
        parts.append("## Latency (seconds per claim, mean)\n\n")
        parts.append(f"- A: {headline_latency.get('lat_a')}, B: {headline_latency.get('lat_b')}, "
                     f"C: {headline_latency.get('lat_c')}, D: {headline_latency.get('lat_d')}.\n\n")

    if not unsupervised.empty:
        parts.append("## Unsupervised evaluation on real queries\n\n")
        parts.append("`unsupported_per_answer` is the share of answer sentences the retrieved corpus does not support. "
                     "`query_entailment` is whether the answer entails the query; it is not a standard answer-relevance score. "
                     "`context_relevance` is a retrieval-level score shared by all conditions.\n\n")
        parts.append(table(unsupervised))
        parts.append("\n")

    if records:
        parts.append("## Structured records used by the numeric check\n\n")
        parts.append("Only records with support at least 2 and an exact source phrase are kept. "
                     "Ambiguous or single-source records are dropped rather than guessed.\n\n")
        rows = [{"key": record["key"], "value": record["value"], "operator": record["operator"],
                 "support": record["support"], "source_doc": record["source_doc"],
                 "source_date": record["source_date"]} for record in records]
        parts.append(table(pd.DataFrame(rows)))
        parts.append("\n")

    parts.append("## Limitations\n\n")
    source_fragment = audit_value("test_real_chunk_fragment")
    source_claims = audit_value("test_real_chunk")
    parts.append("- Claims are constructed from real sentences; perturbed counterfactuals retain their source chunk and original value. "
                 f"{source_fragment} of {source_claims} source-backed test claims are fragmentary; "
                 "the headline therefore uses only source-backed claims and never presents a counterfactual as a fact.\n")
    parts.append(f"- {audit_value('test_unverifiable_hedge')} of {audit_value('test_unverifiable')} test unverifiable claims match hedge/refusal patterns. "
                 "They are generated by an LLM and selected with the same NLI judge used for scoring, so they are excluded from the source-backed headline.\n")
    if not condition.empty:
        scored = condition.set_index("condition")
        d_missed = scored.loc["pred_d", "missed_falsehood_rate"]
        b_missed = scored.loc["pred_b", "missed_falsehood_rate"]
        parts.append(f"- D misses {float(d_missed) * 100:.2f}% of false claims versus B at {float(b_missed) * 100:.2f}%. "
                     "Its advantage is three-way macro-F1 and selective abstention, not a lower falsehood-miss rate.\n")
    if not headline_ablation.empty:
        g_row = headline_ablation[headline_ablation["rule"] == "g_only"]
        c_row = headline_ablation[headline_ablation["rule"] == "cascade"]
        if len(g_row) and len(c_row) and float(g_row["accuracy"].iloc[0]) > float(c_row["accuracy"].iloc[0]):
            parts.append(f"- G-only accuracy ({g_row['accuracy'].iloc[0]}) exceeds cascade ({c_row['accuracy'].iloc[0]}) "
                         "on the source-backed subset. The cascade is not the best rule here.\n")
    mb = headline_stats.get("mcnemar_d_vs_b", {}) if headline_stats else {}
    if mb.get("p_value") is not None:
        parts.append(f"- McNemar D vs B p = {mb.get('p_value')}; this is not below 0.05.\n")
    if baseline.get("claims_completed") == split.get("test_claims"):
        parts.append("- A/B/C predictions were rerun with three-way TRUE/FALSE/UNVERIFIABLE prompts. "
                     "`results/baseline_rerun.json` records the model, seed, sample count and prompt hashes.\n")
        a_row = real[real["condition"] == "A plain LLM"] if not real.empty else pd.DataFrame()
        if len(a_row) and float(a_row["abstention_rate"].iloc[0]) == 1.0:
            parts.append("- Plain LLM A returned UNVERIFIABLE for every source-backed test claim; its zero accuracy is baseline behavior, not a parser failure.\n")
    else:
        parts.append("- The stored baseline predictions were produced with binary YES/NO prompts; the code now asks for three labels, "
                     "so the baseline comparison needs a rerun before it can be treated as a fair three-way comparison.\n")
    parts.append(f"- The corpus is {corpus.get('pdfs_selected', '')} of {total_pdfs} PDFs; the remaining documents are not indexed. "
                 "Scanned PDFs without a text layer are skipped.\n")
    parts.append("- Unsupervised scores are entailment-based, not human judgements. Only one policy rule is active.\n")
    parts.append("- Supervised NITJSR evaluation with independent human labels is deferred; see `TODO.md`.\n\n")

    parts.append("## Reproducibility\n\n")
    parts.append("Every constructed claim retains its `source_chunk_id`, source document and perturbation metadata. "
                 "`reproduce.py` checks that predictions match the test split, that every source-backed claim resolves to its source chunk, "
                 "and that the headline metrics, statistics, ablation, subgroup and latency recompute from `results/test_predictions.csv`.\n\n")
    parts.append("```python\nfrom reproduce import check, ledger\nerrors, rows = check()\nassert not errors\nprint(rows.groupby(['label', 'method']).size())\n```\n\n")
    parts.append("Per-claim provenance and decision: `python reproduce.py --claim T000`. "
                 "The full claim ledger is `results/claim_ledger.csv`.\n\n")
    parts.append("## Reproduce\n\n")
    parts.append("```bash\npython -m venv .venv\n.venv\\Scripts\\activate\npip install -r requirements.txt\n"
                 "ollama pull gemma4:e4b\nollama pull nomic-embed-text\nset AS_OF_DATE=2026-11-24\n"
                 "python select_corpus.py\npython ingest.py\npython index.py\npython claims.py\npython absent.py\n"
                 "python make_split.py\npython evaluate.py --mode all\npython rerun_baselines.py --replace\npython rescore.py\npython reproduce.py --check\npython make_docs.py\n"
                 "python dashboard/build.py\nuvicorn app:app --host 127.0.0.1 --port 8001\n```\n\n")
    parts.append("On Linux/macOS use `source .venv/bin/activate` and `export AS_OF_DATE=2026-11-24` instead. "
                 "The dashboard is served from `dashboard/dist` with `npm install && npm run dev` inside `dashboard/`.\n")

    (ROOT / "README.md").write_text("".join(parts), encoding="utf-8")

    html = ["<html><head><meta charset='utf-8'><title>NITJ verification</title>",
            "<style>body{font-family:system-ui;margin:2rem;max-width:1100px}td,th{border:1px solid #ccc;padding:6px}"
            "th{background:#f2f2f2}</style></head><body>",
            "<h1>Groundedness verification dashboard</h1>",
            f"<p>{corpus.get('chunks_dedup', '')} chunks over {corpus.get('pdfs_parsed', '')} PDFs; "
            f"{index.get('chunks', '')} indexed vectors.</p>"]
    if not real.empty:
        html.append("<h2>Real-chunk test set</h2>" + real.to_html(index=False, border=0))
    if not condition.empty:
        show = condition[["condition", "n", "accuracy", "macro_f1", "missed_falsehood_rate", "abstention_rate"]].copy()
        show["condition"] = show["condition"].map(names)
        html.append("<h2>All test claims</h2>" + show.to_html(index=False, border=0))
    if stats:
        html.append("<h2>Statistics</h2><pre>" + json.dumps(stats, indent=2) + "</pre>")
    if not ablation.empty:
        html.append("<h2>Ablation</h2>" + ablation.to_html(index=False, border=0))
    if records:
        html.append("<h2>Records</h2>" + pd.DataFrame(rows).to_html(index=False, border=0))
    html.append("</body></html>")
    (ROOT / "dashboard.html").write_text("\n".join(html), encoding="utf-8")
    print("wrote README.md and dashboard.html")


if __name__ == "__main__":
    main()
