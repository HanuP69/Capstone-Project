import json

import pandas as pd

from config import DATA, RESULTS, ROOT


def j(name):
    p = DATA / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}


def table(df, cols=None):
    df = df[cols] if cols else df
    head = "| " + " | ".join(df.columns) + " |\n|" + "|".join(["---"] * len(df.columns)) + "|\n"
    rows = "".join("| " + " | ".join(str(v) for v in r) + " |\n" for r in df.itertuples(index=False))
    return head + rows


def main():
    corpus = j("corpus_stats.json")
    index = j("index_manifest.json")
    split = j("split.json")
    stats = json.loads((RESULTS / "stats.json").read_text()) if (RESULTS / "stats.json").exists() else {}
    cond = pd.read_csv(RESULTS / "condition_metrics.csv") if (RESULTS / "condition_metrics.csv").exists() else pd.DataFrame()
    unsup = pd.read_csv(RESULTS / "unsupervised_metrics.csv") if (RESULTS / "unsupervised_metrics.csv").exists() else pd.DataFrame()
    records = pd.read_json(DATA / "records.json") if (DATA / "records.json").exists() else pd.DataFrame()
    ab = pd.read_csv(RESULTS / "ablation.csv") if (RESULTS / "ablation.csv").exists() else pd.DataFrame()
    sg = pd.read_csv(RESULTS / "subgroup_metrics.csv") if (RESULTS / "subgroup_metrics.csv").exists() else pd.DataFrame()
    lat = json.loads((RESULTS / "latency.json").read_text()) if (RESULTS / "latency.json").exists() else {}

    parts = []
    parts.append("# Groundedness Verification for NIT Jamshedpur Academic Queries\n")
    parts.append("Every number in this file is generated by `make_docs.py` from CSV/JSON artifacts produced by the scripts in this repository. "
                 "`check_artifacts.py` fails the build if a number cannot be traced to an artifact.\n")

    parts.append("## Corpus\n")
    parts.append(f"- PDFs selected and parsed: {corpus.get('pdfs_parsed','')} of {corpus.get('pdfs_selected','')} chosen by content coverage from {corpus.get('pdfs_total','')} PDFs\n")
    parts.append(f"- Chunks: {corpus.get('chunks_dedup','')} after removing {corpus.get('duplicates_removed','')} duplicate bodies\n")
    parts.append(f"- Prose chunks: {corpus.get('prose_chunks','')}; table chunks: {corpus.get('table_chunks','')}\n")
    parts.append(f"- Chunks with a parsed issue date: {corpus.get('with_date','')}; with a parsed reference number: {corpus.get('with_ref','')}\n")
    parts.append(f"- Date range: {corpus.get('date_range',['',''])[0]} to {corpus.get('date_range',['',''])[1]}\n")
    parts.append(f"- Median prose chunk: {corpus.get('median_prose_words','')} words (target 240, one-sentence overlap)\n")
    parts.append(f"- Indexed vectors: {index.get('chunks','')} at {index.get('dim','')} dimensions with {index.get('emb_model','')}\n")

    parts.append("\n## Benchmark\n")
    parts.append(f"- Claims: {split.get('total','')} constructed from real chunks with source pointers\n")
    parts.append(f"- Labels: {split.get('labels',{})}\n")
    parts.append(f"- Construction: {split.get('methods',{})}\n")
    parts.append(f"- Group split by source document: {split.get('dev_docs','')} dev documents ({split.get('dev_claims','')} claims), "
                 f"{split.get('test_docs','')} test documents ({split.get('test_claims','')} claims)\n")
    parts.append("- Thresholds and weights were tuned on dev only; test was scored once, after freezing `data/thresholds.json`.\n")

    if not cond.empty:
        parts.append("\n## Main result\n")
        show = cond[["condition", "n", "accuracy", "macro_f1", "missed_falsehood_rate", "abstention_rate"]].copy()
        show["condition"] = show["condition"].map({"pred_a": "A plain LLM", "pred_b": "B RAG", "pred_c": "C self-consistency", "pred_d": "D verified pipeline"})
        parts.append(table(show))
        parts.append("\nPer class:\n")
        for r in cond.itertuples():
            parts.append(f"- {r.condition}: precision {r.per_class_precision}, recall {r.per_class_recall}, f1 {r.per_class_f1}\n")

    if stats:
        parts.append("\n## Statistics\n")
        parts.append(f"- Scored test claims: {stats.get('n_scored','')} (excluded {stats.get('n_excluded_contaminated','')} unverifiable claims that retrieval could actually support)\n")
        mb = stats.get("mcnemar_d_vs_b", {})
        bb = stats.get("bootstrap_d_minus_b", {})
        parts.append(f"- McNemar D vs B: D better on {mb.get('d_better','')}, B better on {mb.get('b_better','')}, p = {mb.get('p_value','')}\n")
        parts.append(f"- Paired bootstrap accuracy delta D - B: {bb.get('delta','')} ({bb.get('ci_low','')} to {bb.get('ci_high','')})\n")
        parts.append(f"- Judge backend: {stats.get('judge_backend','')}\n")
        parts.append(f"- Brier score (D, true/false): {stats.get('brier_d','')}\n")

    if not ab.empty:
        parts.append("\n## Gate ablation (test set)\n")
        parts.append(table(ab))
        if len(ab) > 0:
            cas = ab[ab["rule"] == "cascade"]["accuracy"].iloc[0]
            fonly = ab[ab["rule"] == "f_only"]["accuracy"].iloc[0]
            gonly = ab[ab["rule"] == "g_only"]["accuracy"].iloc[0]
            parts.append(f"\nWeights and G are not identifiable on this feature distribution: cascade ({cas}) and F-only ({fonly}) are within 1 point, "
                         f"and a G-only gate scores {gonly}. The learned-weight calibration claim is withdrawn (F26, F27).\n")

    if not sg.empty:
        parts.append("\n## Subgroup: multi-fact vs single-fact claims (test)\n")
        parts.append(table(sg))

    if lat:
        parts.append("\n## Latency (seconds per claim, mean)\n")
        parts.append(f"- A: {lat.get('lat_a')}, B: {lat.get('lat_b')}, C: {lat.get('lat_c')}, D: {lat.get('lat_d')}\n")

    if not unsup.empty:
        parts.append("\n## Unsupervised evaluation on real queries\n")
        parts.append("Answers are generated by each condition and scored against the corpus by entailment. "
                     "`unsupported_per_answer` is the share of answer sentences the corpus does not support.\n")
        parts.append(table(unsup))

    if not records.empty:
        parts.append("\n## Structured records\n")
        parts.append("Extracted from documents with source pointers; values are used only where the extraction agreed across documents.\n")
        cols = [c for c in ["key", "value", "operator", "support", "source_doc", "source_date"] if c in records.columns]
        parts.append(table(records[cols].head(20)))

    parts.append("\n## Limitations\n")
    parts.append("- Claims are constructed by perturbing a value in a real sentence, so they are easier than natural hallucinations; this is stated rather than hidden.\n")
    parts.append("- Multi-fact claims (concatenated sentences) are harder for all conditions; D reaches 0.40 accuracy vs 0.91 on single-fact claims. Atomic decomposition is a TODO.\n")
    parts.append("- One third of the claim set is model-generated unsupported claims filtered by max entailment < 0.35.\n")
    parts.append("- The corpus is 180 of 2241 PDFs, selected by topical coverage; the remaining documents are not indexed.\n")
    parts.append("- Scanned PDFs without a text layer are not ingested.\n")
    parts.append("- Unsupervised scores use an entailment model on retrieved sentences, not human judgements.\n")
    parts.append("- Only one verified policy rule (ATT_75); policy signal is sparse.\n")
    parts.append("- Weights and G are not identifiable on this data; the cascade is dominated by the numeric check (F).\n")
    parts.append("- Supervised NITJSR evaluation is deferred (TODO.md).\n")

    (ROOT / "README.md").write_text("".join(parts), encoding="utf-8")

    html = ["<html><head><meta charset='utf-8'><title>NITJ verification</title>",
            "<style>body{font-family:system-ui;margin:2rem;max-width:1100px}td,th{border:1px solid #ccc;padding:6px}"
            "th{background:#f2f2f2}</style></head><body>",
            "<h1>Groundedness verification dashboard</h1>",
            f"<p>{corpus.get('chunks_dedup','')} chunks over {corpus.get('pdfs_parsed','')} PDFs; "
            f"{index.get('chunks','')} indexed vectors.</p>"]
    for title, df in (("Test set", cond), ("Unsupervised", unsup)):
        if df.empty:
            continue
        html.append(f"<h2>{title}</h2>")
        html.append(df.to_html(index=False, border=0))
    if stats:
        html.append("<h2>Statistics</h2><pre>" + json.dumps(stats, indent=2) + "</pre>")
    if not ab.empty:
        html.append("<h2>Ablation</h2>" + ab.to_html(index=False, border=0))
    html.append("</body></html>")
    (ROOT / "dashboard.html").write_text("\n".join(html), encoding="utf-8")
    print("wrote README.md and dashboard.html")


if __name__ == "__main__":
    main()
